from collections import defaultdict
from typing import List
class Solution:
    def validPath(self, n: int, edges: List[List[int]], source: int, destination: int) -> bool:
        if source == destination:
            return True

        stack = [source]
        visited = set()
        #bikin graphnya
        graph = defaultdict(list)
        for u, v in edges:
            graph[u].append(v) # graph[u].append(v) dan graph[v].append(u) karena graphnya undirected
            graph[v].append(u) # graph[u].append(v) dan graph[v].append(u) karena graphnya undirecte
        if len(edges) <=0: # kalau edgesnya kosong, berarti ga ada path, kecuali source == destination
            return True # source == destination, karena kalau source == destination, berarti valid pathnya adalah node itu sendiri, jadi valid pathnya tetap ada walaupun edgesnya kosong

        valid_path = False #boolean untuk menandakan apakah valid pathnya ditemukan atau tidak
        while stack: # lakukan DFS dengan stack
            node = stack.pop() # pop








































































































































































































































































































































































































































































































































































































            if node in visited:
                continue
            visited.add(node)
            for neighbor in graph[node]:
                stack.append(neighbor)
                if neighbor == destination:
                    valid_path = True
                    break
            if valid_path:
                break
        return valid_path
            

